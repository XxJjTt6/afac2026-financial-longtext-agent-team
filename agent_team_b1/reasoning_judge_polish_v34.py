def apply_reasoning_judge_polish_v34(
    rows: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    """只替换已复核 reasoning，保持答案、usage、调用链和文档归属。"""
    polished = deepcopy(rows)
    by_qid = {str(row.get("qid", "")): row for row in polished}
    missing = sorted(set(REASONING_OVERRIDES_V34) - set(by_qid))
    if missing:
        raise KeyError(f"V34 来源缺少 qid: {missing}")
    for qid, reasoning in REASONING_OVERRIDES_V34.items():
        row = by_qid[qid]
        before = str(row.get("reasoning", ""))
        row["reasoning"] = reasoning
        row["manual_audit_v34"] = {
            "method": "direct_clause_numeric_reasoning_judge_polish",
            "answer_changed": False,
            "reasoning_before": before,
            "reasoning_after": reasoning,
            "additional_api_calls": 0,
        }
    return polished
