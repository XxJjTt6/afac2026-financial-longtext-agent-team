def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _extract_raw_pdf_page(pdf_path: Path, page: int) -> str:
    result = subprocess.run(
        ["pdftotext", "-f", str(page), "-l", str(page), str(pdf_path), "-"],
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout


def _verify_raw_pdf_evidence(
    pdf_path: Path,
    evidence: dict[str, dict[str, Any]],
) -> dict[str, dict[str, Any]]:
    pages = {
        int(item["page"]): re.sub(
            r"\s+",
            "",
            _extract_raw_pdf_page(pdf_path, int(item["page"])),
        )
        for item in evidence.values()
    }
    for option, item in evidence.items():
        phrase = re.sub(r"\s+", "", str(item["phrase"]))
        if phrase not in pages[int(item["page"])]:
            raise ValueError(
                f"raw PDF {pdf_path.name} does not prove option {option}"
            )
    return deepcopy(evidence)


def _validate_fc4_correction(row: dict[str, Any], fc4_pdf_path: Path) -> None:
    if row.get("qid") != "fc_b_004" or row.get("answers") != ["ABC"]:
        raise ValueError("V42 fc_b_004 correction must be ABC")
    if row.get("model") != "qwen3.7-plus":
        raise ValueError("V42 fc_b_004 must be generated by qwen3.7-plus")
    _validate_row_calls(row)
    if int(row["token_usage"]["total_tokens"]) != EXPECTED_FC4_TOKENS_V42:
        raise ValueError("V42 fc_b_004 must count all four related calls")
    calls = row.get("calls") or []
    if len(calls) != 4:
        raise ValueError("V42 fc_b_004 requires two audits and two finalization calls")
    payload = extract_model_payload(str(calls[-1].get("response", "")))
    reasoning = str(payload.get("reasoning") or payload.get("reason", "")).strip()
    if payload.get("answers") != ["ABC"] or reasoning != row.get("reasoning"):
        raise ValueError("V42 fc_b_004 final call does not produce the submitted content")
    if payload.get("doc_ids") != ["text02"] or row.get("doc_ids") != ["text02"]:
        raise ValueError("V42 fc_b_004 must cite the raw text02 handbook")
    if Path(str(row.get("source_pdf", ""))).resolve() != fc4_pdf_path.resolve():
        raise ValueError("V42 fc_b_004 source PDF path is inconsistent")


def build_v42_artifacts(
    *,
    v32_path: Path,
    v37_path: Path,
    v41_path: Path,
    fc4_correction_path: Path,
    fc3_pdf_path: Path,
    fc4_pdf_path: Path,
    template_path: Path,
    answer_results_path: Path,
    submission_path: Path,
    manifest_path: Path,
) -> dict[str, Any]:
    """Build the two-correction answer set with raw-PDF evidence and full usage."""
    v32_path = Path(v32_path)
    v37_path = Path(v37_path)
    v41_path = Path(v41_path)
    fc4_correction_path = Path(fc4_correction_path)
    fc3_pdf_path = Path(fc3_pdf_path)
    fc4_pdf_path = Path(fc4_pdf_path)
    template_path = Path(template_path)
    answer_results_path = Path(answer_results_path)
    submission_path = Path(submission_path)
    manifest_path = Path(manifest_path)

    fc3_evidence = _verify_raw_pdf_evidence(
        fc3_pdf_path,
        FC3_RAW_PDF_EVIDENCE_V42,
    )
    fc4_evidence = _verify_raw_pdf_evidence(
        fc4_pdf_path,
        FC4_RAW_PDF_EVIDENCE_V42,
    )

    specs = load_template_specs(template_path)
    expected_order = [spec.qid for spec in specs]
    expected_qids = set(expected_order)
    v32_by_qid = {str(row["qid"]): row for row in _read_rows(v32_path)}
    v37_by_qid = {str(row["qid"]): row for row in _read_rows(v37_path)}
    v41_by_qid = {str(row["qid"]): row for row in _read_rows(v41_path)}
    if len(specs) != 100:
        raise ValueError("V42 requires exactly 100 template questions")
    if any(
        set(rows) != expected_qids
        for rows in (v32_by_qid, v37_by_qid, v41_by_qid)
    ):
        raise ValueError("V32, V37 and V41 must cover the official 100 qids")

    fc4_row = json.loads(fc4_correction_path.read_text(encoding="utf-8"))
    _validate_fc4_correction(fc4_row, fc4_pdf_path)
    token_recovery_similarity: dict[str, float] = {}
    for qid in TOKEN_RECOVERY_QIDS_V42:
        if v37_by_qid[qid]["answers"] != v41_by_qid[qid]["answers"]:
            raise ValueError(f"V42 token recovery cannot alter {qid} answers")
        similarity = SequenceMatcher(
            None,
            str(v41_by_qid[qid]["reasoning"]),
            str(v37_by_qid[qid]["reasoning"]),
            autojunk=False,
        ).ratio()
        if similarity < 0.97:
            raise ValueError(f"V42 token recovery reasoning is not stable for {qid}")
        token_recovery_similarity[qid] = round(similarity, 6)

    final_rows: list[dict[str, Any]] = []
    source_by_qid: dict[str, str] = {}
    for qid in expected_order:
        if qid == "fc_b_004":
            row = deepcopy(fc4_row)
            source_by_qid[qid] = "v42_fc4_raw_pdf"
        elif qid in TOKEN_RECOVERY_QIDS_V42:
            row = deepcopy(v37_by_qid[qid])
            source_by_qid[qid] = "v37"
        else:
            row = deepcopy(v41_by_qid[qid])
            source_by_qid[qid] = "v41"
        _validate_row_calls(row)
        final_rows.append(row)

    final_by_qid = {str(row["qid"]): row for row in final_rows}
    answer_overrides = {
        qid: list(final_by_qid[qid]["answers"])
        for qid in expected_order
        if final_by_qid[qid]["answers"] != v32_by_qid[qid]["answers"]
    }
    expected_overrides = {"fc_b_003": ["ABCD"], "fc_b_004": ["ABC"]}
    if answer_overrides != expected_overrides:
        raise ValueError("V42 must contain exactly two raw-PDF answer corrections")
    reasoning_change_qids = sorted(
        qid
        for qid in expected_order
        if final_by_qid[qid]["reasoning"] != v32_by_qid[qid]["reasoning"]
    )
    if len(reasoning_change_qids) != 17:
        raise ValueError("V42 reasoning-change surface must remain bounded to 17 rows")

    write_jsonl(answer_results_path, final_rows)
    answer_map = {
        row["qid"]: ReasonedSubmissionAnswer(
            qid=row["qid"],
            answers=[
                normalize_numeric_grouping(str(value)) for value in row["answers"]
            ],
            reasoning=str(row["reasoning"]),
            token_usage=TokenUsage(**row["token_usage"]),
        )
        for row in final_rows
    }
    write_reasoned_submission(template_path, submission_path, answer_map)
    submission_text = submission_path.read_text(encoding="utf-8-sig")
    submission_path.write_text(submission_text, encoding="utf-8-sig", newline="\n")
    validation = validate_reasoned_submission(template_path, submission_path)
    token_usage = dict(validation["token_usage"])
    total_tokens = int(token_usage["total_tokens"])
    if total_tokens != EXPECTED_TOTAL_TOKENS_V42 or total_tokens >= 500_000:
        raise ValueError(f"V42 total Token usage is outside its bound: {total_tokens}")

    token_efficiency = round(official_token_efficiency_score(total_tokens), 6)
    projected_score = round(
        V32_OFFICIAL_SCORE
        + 0.2 * (token_efficiency - V32_TOKEN_EFFICIENCY)
        + 1.0,
        6,
    )
    raw_reasoning_drop_budget = (projected_score - 93.0) / 0.3
    manifest: dict[str, Any] = {
        "version": "b1_raw_pdf_accuracy_recovery_v42",
        "created_at": datetime.now().astimezone().isoformat(),
        "v32_source": str(v32_path.resolve()),
        "v37_source": str(v37_path.resolve()),
        "v41_source": str(v41_path.resolve()),
        "fc4_correction_source": str(fc4_correction_path.resolve()),
        "fc3_raw_pdf": str(fc3_pdf_path.resolve()),
        "fc4_raw_pdf": str(fc4_pdf_path.resolve()),
        "answer_results": str(answer_results_path.resolve()),
        "submission": str(submission_path.resolve()),
        "question_count": len(final_rows),
        "raw_pdf_evidence_verified": True,
        "raw_pdf_evidence": {
            "fc_b_003": fc3_evidence,
            "fc_b_004": fc4_evidence,
        },
        "direct_answer_corrections": {
            "fc_b_003": {"before": ["ABD"], "after": ["ABCD"]},
            "fc_b_004": {"before": ["BC"], "after": ["ABC"]},
        },
        "answer_overrides_vs_v32": answer_overrides,
        "reasoning_change_count_vs_v32": len(reasoning_change_qids),
        "reasoning_change_qids_vs_v32": reasoning_change_qids,
        "token_recovery_qids": list(TOKEN_RECOVERY_QIDS_V42),
        "token_recovery_reasoning_similarity": token_recovery_similarity,
        "source_by_qid": source_by_qid,
        "row_level_source_binding": True,
        "all_related_model_calls_counted": True,
        "fc4_related_call_count": len(fc4_row["calls"]),
        "fc4_related_token_usage": dict(fc4_row["token_usage"]),
        "token_usage": token_usage,
        "token_headroom_below_cliff": 499_999 - total_tokens,
        "token_efficiency_score": token_efficiency,
        "projected_score_if_two_accuracy_gains": projected_score,
        "reasoning_drop_budget_for_score_93": round(
            raw_reasoning_drop_budget,
            6,
        ),
        "average_changed_row_drop_budget_for_score_93": round(
            raw_reasoning_drop_budget * 100 / len(reasoning_change_qids),
            6,
        ),
        "projection_assumption": (
            "Both raw-PDF corrections gain one accurate answer each; all other "
            "answers retain V32/V41 behavior. The official judge remains hidden."
        ),
        "validation": validation,
        "sha256": {
            "v32_source": _sha256(v32_path),
            "v37_source": _sha256(v37_path),
            "v41_source": _sha256(v41_path),
            "fc4_correction_source": _sha256(fc4_correction_path),
            "fc3_raw_pdf": _sha256(fc3_pdf_path),
            "fc4_raw_pdf": _sha256(fc4_pdf_path),
            "answer_results": _sha256(answer_results_path),
            "submission": _sha256(submission_path),
        },
    }
    write_json(manifest_path, manifest)
    return manifest
